  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL UNIQUE,
  original_payment_id bigint NOT NULL UNIQUE,
  replacement_payment_id bigint UNIQUE,
  adda_id uuid NOT NULL REFERENCES public.addas(id) ON DELETE RESTRICT,
  voucher_id bigint NOT NULL,
  manual_voucher_id uuid NOT NULL,
  diesel_entry_id bigint NOT NULL,
  action text NOT NULL CHECK (action IN ('void','replace')),
  reason text NOT NULL CHECK (pg_catalog.btrim(reason) <> ''),
  request_payload jsonb NOT NULL,
  original_snapshot jsonb NOT NULL,
  replacement_snapshot jsonb,
  result_payload jsonb NOT NULL,
  actor_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  CONSTRAINT manual_voucher_diesel_payment_correction_action_check
    CHECK ((action='void' AND replacement_payment_id IS NULL AND replacement_snapshot IS NULL)
        OR (action='replace' AND replacement_payment_id IS NOT NULL AND replacement_snapshot IS NOT NULL))
