CREATE FUNCTION public.correct_manual_voucher_diesel_payment(
  p_payment_id bigint,
  p_adda_id uuid,
  p_request_id uuid,
  p_action text,
  p_reason text,
  p_replacement_date date,
  p_replacement_amount numeric,
  p_replacement_method text,
  p_replacement_reference text,
  p_replacement_remarks text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=pg_catalog
AS $function$
DECLARE
  actor_id uuid := auth.uid();
  actor_role text;
  actor_adda_id uuid;
  actor_active boolean;
  link_probe record;
  link_row public.manual_voucher_diesel_initial_payments%ROWTYPE;
  voucher_row public.expenses%ROWTYPE;
  detail_row public.manual_voucher_details%ROWTYPE;
  diesel_row public.diesel_entries%ROWTYPE;
  payment_row public.petrol_pump_payments%ROWTYPE;
  pump_adda_id uuid;
  replacement_id bigint;
  normalized_action text := pg_catalog.lower(pg_catalog.btrim(p_action));
  normalized_reason text := pg_catalog.btrim(p_reason);
  normalized_method text := NULLIF(pg_catalog.btrim(p_replacement_method),'');
  normalized_reference text := NULLIF(pg_catalog.btrim(p_replacement_reference),'');
  normalized_remarks text := NULLIF(pg_catalog.btrim(p_replacement_remarks),'');
  normalized_amount numeric(14,2);
  result_value jsonb;
  request_payload_value jsonb;
  existing_payload jsonb;
  existing_result jsonb;
  original_snapshot_value jsonb;
  replacement_snapshot_value jsonb;
  expense_snapshot_before jsonb;
  expense_snapshot_after jsonb;
  settlement_snapshot_before jsonb;
  settlement_snapshot_after jsonb;
  owner_transaction_snapshot_before jsonb;
  owner_transaction_snapshot_after jsonb;
  manual_adjustment_snapshot_before jsonb;
  manual_adjustment_snapshot_after jsonb;
  diesel_total_before numeric(14,2);
  allocation_count integer := 0;
  allocation_total numeric(14,2) := 0;
  cashbook_count integer := 0;
  cashbook_match_count integer := 0;
BEGIN
  IF actor_id IS NULL OR p_payment_id IS NULL OR p_adda_id IS NULL OR p_request_id IS NULL
     OR normalized_action IS NULL OR normalized_action NOT IN ('void','replace')
     OR normalized_reason IS NULL OR normalized_reason='' OR pg_catalog.length(normalized_reason)>2000 THEN
    RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='MANUAL_DIESEL_CORRECTION_INPUT_INVALID';
  END IF;

  SELECT profile.role,profile.adda_id,profile.is_active
  INTO actor_role,actor_adda_id,actor_active
  FROM public.profiles profile
  WHERE profile.id=actor_id;
  IF actor_active IS DISTINCT FROM TRUE
     OR actor_role IS NULL
     OR actor_role NOT IN ('adda_admin','super_admin') THEN
    RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='MANUAL_DIESEL_CORRECTION_ADMIN_REQUIRED';
  END IF;
  IF actor_role='adda_admin' AND actor_adda_id IS DISTINCT FROM p_adda_id THEN
    RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='MANUAL_DIESEL_CORRECTION_ADDA_MISMATCH';
  END IF;
  IF actor_role='super_admin' AND NOT EXISTS (
       SELECT 1 FROM public.addas adda WHERE adda.id=p_adda_id
     ) THEN
    RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='MANUAL_DIESEL_CORRECTION_EXPLICIT_ADDA_REQUIRED';
  END IF;

  IF normalized_action='replace' THEN
    normalized_amount:=pg_catalog.round(COALESCE(p_replacement_amount,0),2)::numeric(14,2);
    IF p_replacement_date IS NULL OR normalized_amount<=0
       OR normalized_amount::text IN ('NaN','Infinity','-Infinity')
       OR normalized_amount IS DISTINCT FROM p_replacement_amount
       OR normalized_method IS NULL
       OR normalized_method NOT IN ('Cash','Bank','Cheque','Online Transfer') THEN
      RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='MANUAL_DIESEL_CORRECTION_REPLACEMENT_INPUT_INVALID';
    END IF;
  ELSE
    IF p_replacement_date IS NOT NULL OR p_replacement_amount IS NOT NULL
       OR p_replacement_method IS NOT NULL OR p_replacement_reference IS NOT NULL
       OR p_replacement_remarks IS NOT NULL THEN
      RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='MANUAL_DIESEL_CORRECTION_VOID_PAYLOAD_INVALID';
    END IF;
  END IF;

  request_payload_value:=pg_catalog.jsonb_build_object(
    'payment_id',p_payment_id,'adda_id',p_adda_id,'action',normalized_action,
    'reason',normalized_reason,'replacement_date',p_replacement_date,
    'replacement_amount',normalized_amount,'replacement_method',normalized_method,
    'replacement_reference',normalized_reference,'replacement_remarks',normalized_remarks
  );
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('manual-diesel-correction-request:'||p_request_id::text,0)
  );

  SELECT correction.request_payload,correction.result_payload
  INTO existing_payload,existing_result
  FROM public.manual_voucher_diesel_payment_corrections correction
  WHERE correction.request_id=p_request_id
  FOR UPDATE;
  IF FOUND THEN
    IF existing_payload IS DISTINCT FROM request_payload_value THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_REQUEST_REUSED';
    END IF;
    RETURN existing_result;
  END IF;

  SELECT link.manual_voucher_id,link.voucher_id
  INTO link_probe
  FROM public.manual_voucher_diesel_initial_payments link
  WHERE link.payment_id=p_payment_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='MANUAL_DIESEL_CORRECTION_LINK_NOT_FOUND';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('manual-voucher:'||link_probe.voucher_id::text,0)
  );

  SELECT voucher.* INTO voucher_row
  FROM public.expenses voucher
  WHERE voucher.id=link_probe.voucher_id
  FOR UPDATE;
  SELECT detail.* INTO detail_row
  FROM public.manual_voucher_details detail
  WHERE detail.id=link_probe.manual_voucher_id
    AND detail.voucher_id=link_probe.voucher_id
  FOR UPDATE;
  IF voucher_row.id IS NULL OR detail_row.id IS NULL
     OR voucher_row.voucher_source IS DISTINCT FROM 'manual'
     OR voucher_row.loading_id IS NOT NULL OR voucher_row.movement_group_id IS NOT NULL
     OR voucher_row.archived_at IS NOT NULL
     OR detail_row.status NOT IN ('draft','finalized')
     OR detail_row.adda_id IS DISTINCT FROM p_adda_id THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_VOUCHER_CONTEXT_INVALID';
  END IF;
  IF NOT EXISTS (
       SELECT 1 FROM public.vehicles vehicle
       WHERE vehicle.id=detail_row.vehicle_id AND vehicle.adda_id=detail_row.adda_id
     ) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_VEHICLE_CONTEXT_INVALID';
  END IF;

  SELECT link.* INTO link_row
  FROM public.manual_voucher_diesel_initial_payments link
  WHERE link.payment_id=p_payment_id
    AND link.voucher_id=voucher_row.id
    AND link.manual_voucher_id=detail_row.id
    AND link.adda_id=p_adda_id
    AND link.vehicle_id=detail_row.vehicle_id
  FOR UPDATE;
  IF NOT FOUND OR link_row.correction_status IS DISTINCT FROM 'active' THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_LINK_NOT_ACTIVE';
  END IF;

  SELECT payment.* INTO payment_row
  FROM public.petrol_pump_payments payment
  WHERE payment.id=p_payment_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='MANUAL_DIESEL_CORRECTION_PAYMENT_NOT_FOUND';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(payment_row.petrol_pump_id::text,0)
  );
  pump_adda_id:=public.ut_validate_petrol_pump_payment_tenant(payment_row.petrol_pump_id);
  IF pump_adda_id IS DISTINCT FROM p_adda_id THEN
    RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='MANUAL_DIESEL_CORRECTION_PUMP_TENANT_MISMATCH';
  END IF;

  IF payment_row.advance_used IS DISTINCT FROM 0
     OR payment_row.payment_now IS DISTINCT FROM link_row.paid_amount
     OR payment_row.amount IS DISTINCT FROM link_row.paid_amount
     OR payment_row.payment_date IS DISTINCT FROM link_row.payment_date
     OR payment_row.payment_method IS DISTINCT FROM link_row.payment_method
     OR payment_row.reference_no IS DISTINCT FROM link_row.reference_no
     OR payment_row.remarks IS DISTINCT FROM link_row.payment_remarks THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_PAYMENT_LINK_DRIFT';
  END IF;

  SELECT diesel.* INTO diesel_row
  FROM public.diesel_entries diesel
  JOIN public.expense_items item
    ON item.id=diesel.expense_item_id
   AND item.expense_id=diesel.expense_id
   AND item.expense_type='Fuel'
   AND item.expense_class='regular_trip'
   AND item.amount=diesel.total_amount
  WHERE diesel.id=link_row.diesel_entry_id
    AND diesel.expense_id=voucher_row.id
    AND diesel.manual_voucher_id=detail_row.id
    AND diesel.manual_request_id=link_row.request_id
    AND diesel.loading_id IS NULL
    AND diesel.vehicle_id=detail_row.vehicle_id
    AND diesel.petrol_pump_id=payment_row.petrol_pump_id
  FOR UPDATE OF diesel,item;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_DIESEL_LINK_INVALID';
  END IF;

  SELECT pg_catalog.count(*)::integer,COALESCE(pg_catalog.sum(allocation.amount),0)::numeric(14,2)
  INTO allocation_count,allocation_total
  FROM public.petrol_pump_payment_allocations allocation
  WHERE allocation.payment_id=p_payment_id AND allocation.diesel_entry_id=diesel_row.id;
  IF allocation_count<>1 OR allocation_total IS DISTINCT FROM link_row.paid_amount
     OR EXISTS (
       SELECT 1 FROM public.petrol_pump_payment_allocations allocation
       WHERE allocation.payment_id=p_payment_id AND allocation.diesel_entry_id<>diesel_row.id
     ) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_ALLOCATION_DRIFT';
  END IF;

  SELECT pg_catalog.count(*)::integer,
         pg_catalog.count(*) FILTER (WHERE cashbook.entry_type='Cash Out'
           AND cashbook.amount=payment_row.payment_now
           AND cashbook.entry_date=payment_row.payment_date
           AND cashbook.payment_method=payment_row.payment_method
           AND cashbook.adda_id=p_adda_id)::integer
  INTO cashbook_count,cashbook_match_count
  FROM public.cashbook_entries cashbook
  WHERE cashbook.reference_type='petrol_pump_payment'
    AND cashbook.reference_id=p_payment_id::text;
  IF cashbook_count<>1 OR cashbook_match_count<>1 THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_CASHBOOK_DRIFT';
  END IF;

  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(item) ORDER BY item.id),'[]'::jsonb)
  INTO expense_snapshot_before
  FROM public.expense_items item WHERE item.expense_id=voucher_row.id;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(settlement) ORDER BY settlement.id),'[]'::jsonb)
  INTO settlement_snapshot_before
  FROM public.manual_vehicle_chakkar_settlements settlement
  WHERE settlement.voucher_id=voucher_row.id;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(transaction_row) ORDER BY transaction_row.id),'[]'::jsonb)
  INTO owner_transaction_snapshot_before
  FROM public.owner_gari_account_transactions transaction_row
  WHERE transaction_row.source_manual_settlement_id IN (
      SELECT settlement.id FROM public.manual_vehicle_chakkar_settlements settlement
      WHERE settlement.voucher_id=voucher_row.id
    )
    OR transaction_row.source_manual_adjustment_id IN (
      SELECT adjustment.id FROM public.manual_voucher_adjustments adjustment
      WHERE adjustment.voucher_id=voucher_row.id
    );
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(adjustment) ORDER BY adjustment.id),'[]'::jsonb)
  INTO manual_adjustment_snapshot_before
  FROM public.manual_voucher_adjustments adjustment WHERE adjustment.voucher_id=voucher_row.id;
  diesel_total_before:=diesel_row.total_amount;

  original_snapshot_value:=pg_catalog.jsonb_build_object(
    'payment_id',payment_row.id,'pump_id',payment_row.petrol_pump_id,
    'date',payment_row.payment_date,'amount',payment_row.amount,
    'advance_used',payment_row.advance_used,'payment_now',payment_row.payment_now,
    'method',payment_row.payment_method,'reference',payment_row.reference_no,
    'remarks',payment_row.remarks,'link_paid_amount',link_row.paid_amount,
    'allocation_amount',allocation_total,'cashbook_count',cashbook_count,
    'voucher_id',voucher_row.id,'manual_voucher_id',detail_row.id,
    'voucher_number',voucher_row.expense_no,'voucher_status',detail_row.status,
    'diesel_entry_id',diesel_row.id,'diesel_total',diesel_row.total_amount,
    'diesel_paid_before',diesel_row.paid_amount,
    'diesel_remaining_before',diesel_row.remaining_amount,
    'diesel_status_before',diesel_row.payment_status
  );

  -- The existing protected delete performs the canonical allocation, pump
  -- advance/payable and Cashbook reversal. The link is temporarily detached
  -- only inside this transaction so its generic locked path remains intact.
  UPDATE public.manual_voucher_diesel_initial_payments link
  SET payment_id=NULL,correction_status='voided'
  WHERE link.request_id=link_row.request_id AND link.payment_id=p_payment_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_LINK_CHANGED';
  END IF;
  PERFORM public.delete_petrol_pump_payment(p_payment_id);

  IF EXISTS (SELECT 1 FROM public.petrol_pump_payments payment WHERE payment.id=p_payment_id)
     OR EXISTS (SELECT 1 FROM public.cashbook_entries cashbook
       WHERE cashbook.reference_type='petrol_pump_payment'
         AND cashbook.reference_id=p_payment_id::text) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_VOID_POSTCONDITION_FAILED';
  END IF;

  IF normalized_action='replace' THEN
    replacement_id:=public.save_petrol_pump_payment(
      NULL,payment_row.petrol_pump_id,p_replacement_date,0,normalized_amount,
      normalized_method,normalized_reference,normalized_remarks
    );
    UPDATE public.manual_voucher_diesel_initial_payments link
    SET payment_id=replacement_id,correction_status='active',
        payment_date=p_replacement_date,paid_amount=normalized_amount,
        payment_method=normalized_method,reference_no=normalized_reference,
        payment_remarks=normalized_remarks
    WHERE link.request_id=link_row.request_id AND link.correction_status='voided'
      AND link.payment_id IS NULL;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_REPLACEMENT_LINK_POSTCONDITION_FAILED';
    END IF;
    PERFORM public.rebuild_petrol_pump_accounting(payment_row.petrol_pump_id);

    SELECT pg_catalog.count(*)::integer,COALESCE(pg_catalog.sum(allocation.amount),0)::numeric(14,2)
    INTO allocation_count,allocation_total
    FROM public.petrol_pump_payment_allocations allocation
    WHERE allocation.payment_id=replacement_id AND allocation.diesel_entry_id=diesel_row.id;
    IF allocation_count<>1 OR allocation_total IS DISTINCT FROM normalized_amount
       OR EXISTS (SELECT 1 FROM public.petrol_pump_payment_allocations allocation
          WHERE allocation.payment_id=replacement_id AND allocation.diesel_entry_id<>diesel_row.id)
       OR EXISTS (SELECT 1 FROM public.petrol_pump_payments payment
          WHERE payment.id=replacement_id AND (payment.advance_used IS DISTINCT FROM 0
            OR payment.payment_now IS DISTINCT FROM normalized_amount
            OR payment.amount IS DISTINCT FROM normalized_amount
            OR payment.advance_created IS DISTINCT FROM 0)) THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_REPLACEMENT_ALLOCATION_MISMATCH';
    END IF;
    SELECT pg_catalog.count(*)::integer INTO cashbook_match_count
    FROM public.cashbook_entries cashbook
    WHERE cashbook.reference_type='petrol_pump_payment'
      AND cashbook.reference_id=replacement_id::text
      AND cashbook.entry_type='Cash Out'
      AND cashbook.amount=normalized_amount
      AND cashbook.entry_date=p_replacement_date
      AND cashbook.payment_method=normalized_method
      AND cashbook.adda_id=p_adda_id;
    IF cashbook_match_count<>1 THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_REPLACEMENT_CASHBOOK_MISMATCH';
    END IF;
    SELECT pg_catalog.to_jsonb(payment) INTO replacement_snapshot_value
    FROM public.petrol_pump_payments payment WHERE payment.id=replacement_id;
  END IF;

  SELECT diesel.* INTO diesel_row
  FROM public.diesel_entries diesel WHERE diesel.id=link_row.diesel_entry_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_DIESEL_POSTCONDITION_FAILED';
  END IF;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(item) ORDER BY item.id),'[]'::jsonb)
  INTO expense_snapshot_after
  FROM public.expense_items item WHERE item.expense_id=voucher_row.id;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(settlement) ORDER BY settlement.id),'[]'::jsonb)
  INTO settlement_snapshot_after
  FROM public.manual_vehicle_chakkar_settlements settlement
  WHERE settlement.voucher_id=voucher_row.id;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(transaction_row) ORDER BY transaction_row.id),'[]'::jsonb)
  INTO owner_transaction_snapshot_after
  FROM public.owner_gari_account_transactions transaction_row
  WHERE transaction_row.source_manual_settlement_id IN (
      SELECT settlement.id FROM public.manual_vehicle_chakkar_settlements settlement
      WHERE settlement.voucher_id=voucher_row.id
    )
    OR transaction_row.source_manual_adjustment_id IN (
      SELECT adjustment.id FROM public.manual_voucher_adjustments adjustment
      WHERE adjustment.voucher_id=voucher_row.id
    );
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.to_jsonb(adjustment) ORDER BY adjustment.id),'[]'::jsonb)
  INTO manual_adjustment_snapshot_after
  FROM public.manual_voucher_adjustments adjustment WHERE adjustment.voucher_id=voucher_row.id;
  IF expense_snapshot_before IS DISTINCT FROM expense_snapshot_after
     OR settlement_snapshot_before IS DISTINCT FROM settlement_snapshot_after
     OR owner_transaction_snapshot_before IS DISTINCT FROM owner_transaction_snapshot_after
     OR manual_adjustment_snapshot_before IS DISTINCT FROM manual_adjustment_snapshot_after
     OR diesel_total_before IS DISTINCT FROM diesel_row.total_amount THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_FINANCIAL_SNAPSHOT_CHANGED';
  END IF;

  IF normalized_action='replace' THEN
    SELECT pg_catalog.count(*)::integer INTO cashbook_match_count
    FROM public.cashbook_entries cashbook
    WHERE cashbook.reference_type='petrol_pump_payment'
      AND cashbook.reference_id=replacement_id::text;
    IF cashbook_match_count<>1 THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='MANUAL_DIESEL_CORRECTION_REPLACEMENT_CASHBOOK_DUPLICATE';
    END IF;
  END IF;

  result_value:=pg_catalog.jsonb_build_object(
    'action',normalized_action,'original_payment_id',p_payment_id,
    'replacement_payment_id',replacement_id,'voucher_id',voucher_row.id,
    'voucher_number',voucher_row.expense_no,'manual_voucher_id',detail_row.id,
    'diesel_entry_id',diesel_row.id,'diesel_total',diesel_row.total_amount,
    'diesel_paid',diesel_row.paid_amount,'diesel_remaining',diesel_row.remaining_amount,
    'diesel_status',diesel_row.payment_status,'reason',normalized_reason,
    'corrected_at',pg_catalog.transaction_timestamp()
  );
  INSERT INTO public.manual_voucher_diesel_payment_corrections(
    request_id,original_payment_id,replacement_payment_id,adda_id,voucher_id,
    manual_voucher_id,diesel_entry_id,action,reason,request_payload,
    original_snapshot,replacement_snapshot,result_payload,actor_id
  ) VALUES (
    p_request_id,p_payment_id,replacement_id,p_adda_id,voucher_row.id,
    detail_row.id,diesel_row.id,normalized_action,normalized_reason,
    request_payload_value,original_snapshot_value,replacement_snapshot_value,
    result_value,actor_id
  );
  RETURN result_value;
END
$function$;

