create or replace function public.save_workshop_entry_with_items(
  p_entry_id bigint,
  p_work_date date,
  p_vehicle_id uuid,
  p_workshop_id uuid,
  p_mechanic_name text,
  p_bill_no text,
  p_paid_amount numeric,
  p_next_service_date date,
  p_odometer bigint,
  p_remarks text,
  p_parts_cost numeric,
  p_labour_cost numeric,
  p_items jsonb
) returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_entry_id bigint;
  v_existing_workshop_id uuid;
  v_adda_id uuid;
  v_workshop_name text;
  v_total numeric;
  v_paid numeric := coalesce(p_paid_amount, 0);
  v_item jsonb;
  v_quantity numeric;
  v_rate numeric;
  v_work_summary text;
begin
  if auth.uid() is null or public.current_user_role() is null then
    raise exception 'AUTHORIZATION_FAILED';
  end if;
  if p_work_date is null or p_vehicle_id is null or p_workshop_id is null then
    raise exception 'REQUIRED_FIELDS_MISSING';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'WORK_ITEMS_REQUIRED';
  end if;

  select workshop.adda_id, workshop.workshop_name into v_adda_id, v_workshop_name
  from public.workshops workshop where workshop.id = p_workshop_id;
  if v_adda_id is null then raise exception 'WORKSHOP_NOT_FOUND'; end if;
  if not public.is_super_admin() and v_adda_id is distinct from public.current_user_adda_id() then
    raise exception 'TENANT_MISMATCH';
  end if;
  if not exists (select 1 from public.vehicles vehicle where vehicle.id=p_vehicle_id and vehicle.adda_id=v_adda_id) then
    raise exception 'VEHICLE_TENANT_MISMATCH';
  end if;

  v_total := 0;
  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if nullif(btrim(v_item->>'work_type'), '') is null then raise exception 'WORK_TYPE_REQUIRED'; end if;
    v_quantity := nullif(v_item->>'quantity', '')::numeric;
    v_rate := nullif(v_item->>'rate', '')::numeric;
    if v_quantity is null or v_quantity <= 0 or v_rate is null or v_rate < 0 then
      raise exception 'INVALID_WORK_ITEM_AMOUNT';
    end if;
    v_total := v_total + (v_quantity * v_rate);
  end loop;
  if v_total <= 0 or v_paid < 0 or v_paid > v_total then raise exception 'INVALID_WORKSHOP_TOTAL'; end if;
  v_work_summary := btrim((p_items->0->>'work_type')) || case when jsonb_array_length(p_items)>1 then ' +' || (jsonb_array_length(p_items)-1)::text else '' end;

  if p_entry_id is null then
    insert into public.workshop_entries(work_date,vehicle_id,workshop_id,workshop_name,mechanic_name,work_type,bill_no,parts_cost,labour_cost,total_cost,paid_amount,remaining_amount,payment_status,next_service_date,odometer,remarks,adda_id)
    values(p_work_date,p_vehicle_id,p_workshop_id,v_workshop_name,nullif(btrim(p_mechanic_name),''),v_work_summary,nullif(btrim(p_bill_no),''),coalesce(p_parts_cost,0),coalesce(p_labour_cost,0),v_total,v_paid,v_total-v_paid,case when v_paid<=0 then 'Unpaid' when v_paid>=v_total then 'Paid' else 'Partial' end,p_next_service_date,p_odometer,nullif(btrim(p_remarks),''),v_adda_id)
    returning id into v_entry_id;
  else
    select id, workshop_id into v_entry_id, v_existing_workshop_id from public.workshop_entries where id=p_entry_id and adda_id=v_adda_id for update;
    if v_entry_id is null then raise exception 'WORKSHOP_ENTRY_NOT_FOUND'; end if;
    if v_existing_workshop_id is distinct from p_workshop_id then raise exception 'WORKSHOP_CHANGE_NOT_ALLOWED'; end if;
    update public.workshop_entries set work_date=p_work_date,vehicle_id=p_vehicle_id,workshop_id=p_workshop_id,workshop_name=v_workshop_name,mechanic_name=nullif(btrim(p_mechanic_name),''),work_type=v_work_summary,bill_no=nullif(btrim(p_bill_no),''),parts_cost=coalesce(p_parts_cost,0),labour_cost=coalesce(p_labour_cost,0),total_cost=v_total,paid_amount=v_paid,remaining_amount=v_total-v_paid,payment_status=case when v_paid<=0 then 'Unpaid' when v_paid>=v_total then 'Paid' else 'Partial' end,next_service_date=p_next_service_date,odometer=p_odometer,remarks=nullif(btrim(p_remarks),'') where id=v_entry_id;
    delete from public.workshop_entry_items where workshop_entry_id=v_entry_id;
  end if;

  insert into public.workshop_entry_items(workshop_entry_id,line_no,work_type,category,quantity,rate,amount,remarks)
  select v_entry_id, ordinal::integer, btrim(item->>'work_type'), nullif(btrim(item->>'category'),''), (item->>'quantity')::numeric, (item->>'rate')::numeric, (item->>'quantity')::numeric*(item->>'rate')::numeric, nullif(btrim(item->>'remarks'),'')
  from jsonb_array_elements(p_items) with ordinality as source(item, ordinal);
  return v_entry_id;
end;
$$;

revoke all on function public.save_workshop_entry_with_items(bigint,date,uuid,uuid,text,text,numeric,date,bigint,text,numeric,numeric,jsonb) from public;
grant execute on function public.save_workshop_entry_with_items(bigint,date,uuid,uuid,text,text,numeric,date,bigint,text,numeric,numeric,jsonb) to authenticated;

