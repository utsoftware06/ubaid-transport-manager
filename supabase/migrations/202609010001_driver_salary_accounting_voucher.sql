create function public.ut_protect_driver_accounting()
returns trigger language plpgsql set search_path='' as $$
begin
  if coalesce(pg_catalog.current_setting('ut.driver_accounting_sync',true),'')<>'on' then
    raise exception using errcode='42501',message='Driver accounting rows must be changed through approved RPCs';
  end if;
  return case when tg_op='DELETE' then old else new end;
end $$;
create trigger driver_earnings_protect before insert or update or delete on public.driver_earnings
  for each row execute function public.ut_protect_driver_accounting();
create trigger driver_payments_protect before insert or update or delete on public.driver_payments
  for each row execute function public.ut_protect_driver_accounting();
create trigger driver_payment_allocations_protect before insert or update or delete on public.driver_payment_allocations
  for each row execute function public.ut_protect_driver_accounting();

