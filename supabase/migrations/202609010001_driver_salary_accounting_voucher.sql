create function public.ut_protect_driver_cashbook()
returns trigger language plpgsql set search_path='' as $$
declare protected boolean;
begin
  protected:=case when tg_op='DELETE' then old.reference_type='driver_payment'
    else new.reference_type='driver_payment' or (tg_op='UPDATE' and old.reference_type='driver_payment') end;
  if protected and coalesce(pg_catalog.current_setting('ut.cashbook_sync',true),'')<>'on' then
    raise exception using errcode='42501',message='Driver payment Cashbook rows must be changed through Driver Account';
  end if;
  return case when tg_op='DELETE' then old else new end;
end $$;
create trigger cashbook_entries_protect_driver_payment before insert or update or delete on public.cashbook_entries
  for each row execute function public.ut_protect_driver_cashbook();

create function public.rebuild_driver_accounting(p_driver_id uuid)
returns void language plpgsql security definer set search_path='' as $$
declare
  driver_row record;
  payment_row record;
  earning_row record;
  opening_amount numeric;
  opening_due numeric;
  available_advance numeric;
  current_payable numeric;
  actual_advance_used numeric;
  settlement_remaining numeric;
  applied_amount numeric;
  opening_applied_this_payment numeric;
  created_advance numeric;
begin
  select d.id,d.adda_id,d.name,d.opening_balance into driver_row
  from public.drivers d where d.id=p_driver_id for update;
  if not found then raise exception using errcode='P0002',message='Driver not found'; end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_driver_id::text,910001));
  perform pg_catalog.set_config('ut.driver_accounting_sync','on',true);
  perform pg_catalog.set_config('ut.cashbook_sync','on',true);

  delete from public.driver_payment_allocations allocation_row
  using public.driver_payments payment_source
  where allocation_row.payment_id=payment_source.id and payment_source.driver_id=p_driver_id;

  update public.driver_earnings
  set paid_amount=0,
      remaining_amount=greatest(net_payable,0),
      payment_status=case when net_payable<0 then 'recoverable' when net_payable=0 then 'paid' else 'unpaid' end,
      updated_at=pg_catalog.now()
  where driver_id=p_driver_id;

  opening_amount:=coalesce(driver_row.opening_balance,0);
  opening_due:=greatest(opening_amount,0);
  select greatest(-opening_amount,0)+coalesce(sum(greatest(-earning.net_payable,0)),0)
    into available_advance from public.driver_earnings earning where earning.driver_id=p_driver_id;

  for payment_row in
    select payment.* from public.driver_payments payment
    where payment.driver_id=p_driver_id
    order by payment.payment_date,payment.created_at,payment.id
    for update
  loop
    select opening_due+coalesce(sum(earning.remaining_amount),0) into current_payable
    from public.driver_earnings earning where earning.driver_id=p_driver_id;

    actual_advance_used:=least(coalesce(payment_row.advance_used,0),available_advance,current_payable);
    settlement_remaining:=actual_advance_used+coalesce(payment_row.payment_now,0);
    available_advance:=available_advance-actual_advance_used;
    created_advance:=0;

    applied_amount:=least(settlement_remaining,opening_due);
    opening_applied_this_payment:=applied_amount;
    opening_due:=opening_due-applied_amount;
    settlement_remaining:=settlement_remaining-applied_amount;

    for earning_row in
      select earning.* from public.driver_earnings earning
      where earning.driver_id=p_driver_id and earning.remaining_amount>0
      order by earning.salary_date,earning.created_at,earning.id
      for update
    loop
      exit when settlement_remaining<=0;
      applied_amount:=least(settlement_remaining,earning_row.remaining_amount);
      insert into public.driver_payment_allocations(adda_id,payment_id,driver_earning_id,amount)
      values(driver_row.adda_id,payment_row.id,earning_row.id,applied_amount);
      update public.driver_earnings
      set paid_amount=paid_amount+applied_amount,
          remaining_amount=remaining_amount-applied_amount,
          payment_status=case when remaining_amount-applied_amount=0 then 'paid' else 'partial' end,
          updated_at=pg_catalog.now()
      where id=earning_row.id;
      settlement_remaining:=settlement_remaining-applied_amount;
    end loop;

    if settlement_remaining>0 then
      created_advance:=settlement_remaining;
      available_advance:=available_advance+settlement_remaining;
    end if;

    select opening_due+coalesce(sum(earning.remaining_amount),0) into current_payable
    from public.driver_earnings earning where earning.driver_id=p_driver_id;

    update public.driver_payments
    set advance_used=actual_advance_used,
        amount=actual_advance_used+coalesce(payment_now,0),
        opening_applied=opening_applied_this_payment,
        advance_created=created_advance,
        available_advance_before=available_advance+actual_advance_used-created_advance,
        current_payable_before=current_payable+(actual_advance_used+coalesce(payment_now,0)-created_advance),
        remaining_payable=current_payable,
        remaining_advance=available_advance,
        settlement_status=case when current_payable>0 then 'payable' when available_advance>0 then 'advance' else 'paid' end,
        accounting_version=1,updated_at=pg_catalog.now()
    where id=payment_row.id;

    if coalesce(payment_row.payment_now,0)>0 then
      insert into public.cashbook_entries(
        entry_date,entry_type,person_type,person_name,vehicle_id,driver_id,loading_id,
        payment_method,amount,description,reference_type,reference_id
      ) values(
        payment_row.payment_date,'Cash Out','Driver',coalesce(driver_row.name,'Driver'),null,p_driver_id,null,
        coalesce(nullif(payment_row.payment_method,''),'Cash'),payment_row.payment_now,
        'Driver payment - '||coalesce(driver_row.name,'Driver'),'driver_payment',payment_row.id::text
      ) on conflict(reference_type,reference_id)
        where reference_type='driver_payment' and reference_id is not null
      do update set entry_date=excluded.entry_date,entry_type=excluded.entry_type,
        person_type=excluded.person_type,person_name=excluded.person_name,
        vehicle_id=excluded.vehicle_id,driver_id=excluded.driver_id,loading_id=excluded.loading_id,
        payment_method=excluded.payment_method,amount=excluded.amount,description=excluded.description;
    else
      delete from public.cashbook_entries
      where reference_type='driver_payment' and reference_id=payment_row.id::text;
    end if;
  end loop;
end $$;

create function public.save_driver_earning(
  p_earning_id uuid,p_driver_id uuid,p_salary_date date,p_salary_month date,
  p_period_start date,p_period_end date,p_earning_type text,
  p_basic_salary numeric,p_trip_pay numeric,p_bonus_allowance numeric,p_other_earnings numeric,
  p_deduction_fine numeric,p_advance_adjusted numeric,p_remarks text
) returns uuid language plpgsql security definer set search_path='' as $$
declare
  driver_row record;
  resolved_assignment_id uuid;
  resolved_vehicle_id uuid;
  assignment_count integer;
  earning_id uuid;
  earned_amount numeric;
  gross_amount numeric;
  adjusted_amount numeric;
begin
  if auth.uid() is null or public.current_user_role() not in('super_admin','adda_admin','operator') then
    raise exception using errcode='42501',message='Unauthorized Driver earning write';
  end if;
  if p_driver_id is null or p_salary_date is null or p_salary_month is null then
    raise exception using errcode='22004',message='Driver, salary date and salary month are required';
  end if;
  select d.id,d.adda_id into driver_row from public.drivers d where d.id=p_driver_id for update;
  if not found then raise exception using errcode='P0002',message='Driver not found'; end if;
  if not public.is_super_admin() and driver_row.adda_id is distinct from public.current_user_adda_id() then
    raise exception using errcode='42501',message='Driver belongs to another Adda';
  end if;
  if p_salary_month<>date_trunc('month',p_salary_month)::date then
    raise exception using errcode='22007',message='Salary month must be the first calendar day of its month';
  end if;
  if p_period_start is not null and p_period_end is not null and p_period_start>p_period_end then
    raise exception using errcode='22007',message='Earning period start cannot be after period end';
  end if;
  if coalesce(nullif(pg_catalog.btrim(p_earning_type),''),'')='' then
    raise exception using errcode='22023',message='Earning type is required';
  end if;
  if exists(select 1 from unnest(array[coalesce(p_basic_salary,0),coalesce(p_trip_pay,0),coalesce(p_bonus_allowance,0),coalesce(p_other_earnings,0),coalesce(p_deduction_fine,0),coalesce(p_advance_adjusted,0)]) as amount_value(value) where value<0 or value::text in('NaN','Infinity','-Infinity')) then
    raise exception using errcode='22003',message='Driver earning amounts must be finite and non-negative';
  end if;

  select count(*) into assignment_count from public.driver_vehicle_assignments assignment
  where assignment.driver_id=p_driver_id and assignment.adda_id=driver_row.adda_id
    and assignment.start_date<=p_salary_date
    and (assignment.end_date is null or assignment.end_date>=p_salary_date);
  if assignment_count<>1 then
    raise exception using errcode='23514',message='Exactly one Driver assignment must cover the salary date';
  end if;
  select assignment.id,assignment.vehicle_id into resolved_assignment_id,resolved_vehicle_id
  from public.driver_vehicle_assignments assignment
  where assignment.driver_id=p_driver_id and assignment.adda_id=driver_row.adda_id
    and assignment.start_date<=p_salary_date
    and (assignment.end_date is null or assignment.end_date>=p_salary_date);

  earned_amount:=coalesce(p_basic_salary,0)+coalesce(p_trip_pay,0)+coalesce(p_bonus_allowance,0)+coalesce(p_other_earnings,0);
  if coalesce(p_deduction_fine,0)>earned_amount then
    raise exception using errcode='23514',message='Driver deduction cannot exceed earned amount';
  end if;
  gross_amount:=earned_amount-coalesce(p_deduction_fine,0);
  adjusted_amount:=coalesce(p_advance_adjusted,0);
  perform pg_catalog.set_config('ut.driver_accounting_sync','on',true);

  if p_earning_id is null then
    insert into public.driver_earnings(
      adda_id,driver_id,vehicle_id,driver_vehicle_assignment_id,salary_date,salary_month,period_start,period_end,earning_type,
      basic_salary,trip_pay,bonus_allowance,other_earnings,deduction_fine,earned_before_deductions,gross_expense,
      advance_adjusted,net_payable,remaining_amount,payment_status,remarks
    ) values(
      driver_row.adda_id,p_driver_id,resolved_vehicle_id,resolved_assignment_id,p_salary_date,p_salary_month,p_period_start,p_period_end,pg_catalog.btrim(p_earning_type),
      coalesce(p_basic_salary,0),coalesce(p_trip_pay,0),coalesce(p_bonus_allowance,0),coalesce(p_other_earnings,0),coalesce(p_deduction_fine,0),earned_amount,gross_amount,
      adjusted_amount,gross_amount-adjusted_amount,greatest(gross_amount-adjusted_amount,0),
      case when gross_amount-adjusted_amount<0 then 'recoverable' when gross_amount-adjusted_amount=0 then 'paid' else 'unpaid' end,
      nullif(pg_catalog.btrim(p_remarks),'')
    ) returning id into earning_id;
  else
    select earning.id into earning_id from public.driver_earnings earning
    where earning.id=p_earning_id and earning.driver_id=p_driver_id for update;
    if not found then raise exception using errcode='P0002',message='Driver earning not found or Driver cannot be changed'; end if;
    if exists(select 1 from public.voucher_driver_earnings link where link.driver_earning_id=earning_id) then
      raise exception using errcode='23503',message='Unlink the Driver earning from its Voucher before editing';
    end if;
    update public.driver_earnings set
      vehicle_id=resolved_vehicle_id,driver_vehicle_assignment_id=resolved_assignment_id,
      salary_date=p_salary_date,salary_month=p_salary_month,period_start=p_period_start,period_end=p_period_end,
      earning_type=pg_catalog.btrim(p_earning_type),basic_salary=coalesce(p_basic_salary,0),trip_pay=coalesce(p_trip_pay,0),
      bonus_allowance=coalesce(p_bonus_allowance,0),other_earnings=coalesce(p_other_earnings,0),deduction_fine=coalesce(p_deduction_fine,0),
      earned_before_deductions=earned_amount,gross_expense=gross_amount,advance_adjusted=adjusted_amount,
      net_payable=gross_amount-adjusted_amount,remarks=nullif(pg_catalog.btrim(p_remarks),''),updated_at=pg_catalog.now()
    where id=earning_id;
  end if;
  perform public.rebuild_driver_accounting(p_driver_id);
  return earning_id;
end $$;

create function public.delete_driver_earning(p_earning_id uuid)
returns void language plpgsql security definer set search_path='' as $$
declare earning_row record;
begin
  select earning.id,earning.driver_id,earning.adda_id into earning_row
  from public.driver_earnings earning where earning.id=p_earning_id for update;
  if not found then raise exception using errcode='P0002',message='Driver earning not found'; end if;
  if auth.uid() is null or public.current_user_role() not in('super_admin','adda_admin','operator')
     or (not public.is_super_admin() and earning_row.adda_id is distinct from public.current_user_adda_id()) then
    raise exception using errcode='42501',message='Unauthorized Driver earning delete';
  end if;
  if exists(select 1 from public.voucher_driver_earnings link where link.driver_earning_id=p_earning_id) then
    raise exception using errcode='23503',message='Linked Driver earning cannot be deleted';
  end if;
  if exists(select 1 from public.driver_payment_allocations allocation where allocation.driver_earning_id=p_earning_id) then
    raise exception using errcode='23503',message='Settled Driver earning cannot be deleted';
  end if;
  perform pg_catalog.set_config('ut.driver_accounting_sync','on',true);
  delete from public.driver_earnings where id=p_earning_id;
  perform public.rebuild_driver_accounting(earning_row.driver_id);
end $$;

create function public.save_driver_payment(
  p_payment_id bigint,p_driver_id uuid,p_payment_date date,p_advance_used numeric,p_payment_now numeric,
  p_payment_method text,p_reference_no text,p_remarks text
) returns bigint language plpgsql security definer set search_path='' as $$
declare driver_row record;payment_id bigint;advance_amount numeric:=coalesce(p_advance_used,0);cash_amount numeric:=coalesce(p_payment_now,0);
begin
  if auth.uid() is null or public.current_user_role() not in('super_admin','adda_admin','operator') then
    raise exception using errcode='42501',message='Unauthorized Driver payment write';
  end if;
  select d.id,d.adda_id into driver_row from public.drivers d where d.id=p_driver_id for update;
  if not found then raise exception using errcode='P0002',message='Driver not found'; end if;
  if not public.is_super_admin() and driver_row.adda_id is distinct from public.current_user_adda_id() then
    raise exception using errcode='42501',message='Driver belongs to another Adda';
  end if;
  if p_payment_date is null or advance_amount<0 or cash_amount<0 or advance_amount+cash_amount<=0
     or advance_amount::text in('NaN','Infinity','-Infinity') or cash_amount::text in('NaN','Infinity','-Infinity') then
    raise exception using errcode='22023',message='A finite positive Driver settlement is required';
  end if;
  perform pg_catalog.set_config('ut.driver_accounting_sync','on',true);
  if p_payment_id is null then
    insert into public.driver_payments(adda_id,driver_id,payment_date,amount,advance_used,payment_now,payment_method,reference_no,remarks)
    values(driver_row.adda_id,p_driver_id,p_payment_date,advance_amount+cash_amount,advance_amount,cash_amount,
      nullif(pg_catalog.btrim(p_payment_method),''),nullif(pg_catalog.btrim(p_reference_no),''),nullif(pg_catalog.btrim(p_remarks),''))
    returning id into payment_id;
  else
    select payment.id into payment_id from public.driver_payments payment
    where payment.id=p_payment_id and payment.driver_id=p_driver_id for update;
    if not found then raise exception using errcode='P0002',message='Driver payment not found or Driver cannot be changed'; end if;
    update public.driver_payments set payment_date=p_payment_date,amount=advance_amount+cash_amount,
      advance_used=advance_amount,payment_now=cash_amount,payment_method=nullif(pg_catalog.btrim(p_payment_method),''),
      reference_no=nullif(pg_catalog.btrim(p_reference_no),''),remarks=nullif(pg_catalog.btrim(p_remarks),''),updated_at=pg_catalog.now()
    where id=payment_id;
  end if;
  perform public.rebuild_driver_accounting(p_driver_id);
  return payment_id;
end $$;

create function public.delete_driver_payment(p_payment_id bigint)
returns void language plpgsql security definer set search_path='' as $$
declare payment_row record;
begin
  select payment.id,payment.driver_id,payment.adda_id into payment_row
  from public.driver_payments payment where payment.id=p_payment_id for update;
  if not found then raise exception using errcode='P0002',message='Driver payment not found'; end if;
  if auth.uid() is null or public.current_user_role() not in('super_admin','adda_admin','operator')
     or (not public.is_super_admin() and payment_row.adda_id is distinct from public.current_user_adda_id()) then
    raise exception using errcode='42501',message='Unauthorized Driver payment delete';
  end if;
  perform pg_catalog.set_config('ut.driver_accounting_sync','on',true);
  perform pg_catalog.set_config('ut.cashbook_sync','on',true);
  delete from public.cashbook_entries where reference_type='driver_payment' and reference_id=p_payment_id::text;
  delete from public.driver_payments where id=p_payment_id;
  perform public.rebuild_driver_accounting(payment_row.driver_id);
end $$;

