create function public.sync_voucher_driver_earnings(p_voucher_id bigint,p_driver_earning_ids uuid[])
returns void language plpgsql security definer set search_path='' as $$
declare voucher_row record;requested_count integer;valid_count integer;requested_total numeric;item_count integer;item_total numeric;
begin
  if auth.uid() is null or public.current_user_role() not in('super_admin','adda_admin','operator') then
    raise exception using errcode='42501',message='Unauthorized Voucher Driver linkage';
  end if;
  select voucher.id,context_adda.id adda_id,loading.vehicle_id into voucher_row
  from public.expenses voucher
  join public.loadings loading on loading.id=voucher.loading_id
  left join public.bookings booking on booking.id=loading.booking_id
  join public.vehicles vehicle on vehicle.id=loading.vehicle_id
  join public.addas context_adda on context_adda.id=case when loading.booking_id is null then vehicle.adda_id else booking.adda_id end
  where voucher.id=p_voucher_id and (loading.booking_id is null or booking.id is not null)
  for update of voucher;
  if not found then raise exception using errcode='P0002',message='Voucher or tenant/Vehicle context not found'; end if;
  if not public.is_super_admin() and voucher_row.adda_id is distinct from public.current_user_adda_id() then
    raise exception using errcode='42501',message='Voucher belongs to another Adda';
  end if;
  select count(*) into requested_count from(select distinct unnest(coalesce(p_driver_earning_ids,array[]::uuid[])) id) requested;
  if requested_count<>coalesce(array_length(p_driver_earning_ids,1),0) then
    raise exception using errcode='23514',message='Duplicate Driver earning selection';
  end if;
  select count(*) into valid_count from public.driver_earnings earning
  where earning.id=any(coalesce(p_driver_earning_ids,array[]::uuid[]))
    and earning.adda_id=voucher_row.adda_id and earning.vehicle_id=voucher_row.vehicle_id and earning.gross_expense>0
    and not exists(select 1 from public.voucher_driver_earnings link where link.driver_earning_id=earning.id and link.voucher_id<>p_voucher_id);
  if valid_count<>requested_count then
    raise exception using errcode='23514',message='Driver earning is unavailable, invalid, or outside the Voucher Vehicle/Adda';
  end if;
  select coalesce(sum(gross_expense),0) into requested_total from public.driver_earnings
  where id=any(coalesce(p_driver_earning_ids,array[]::uuid[]));
  select count(*),coalesce(sum(amount),0) into item_count,item_total from public.expense_items
  where expense_id=p_voucher_id and expense_type='Driver Salary' and expense_class='vehicle_periodic';
  if (requested_count=0 and item_count<>0) or (requested_count>0 and (item_count<>1 or item_total<>requested_total)) then
    raise exception using errcode='23514',message='Driver Salary Voucher item must exactly match selected persisted gross expense totals';
  end if;
  delete from public.voucher_driver_earnings where voucher_id=p_voucher_id
    and not(driver_earning_id=any(coalesce(p_driver_earning_ids,array[]::uuid[])));
  insert into public.voucher_driver_earnings(adda_id,voucher_id,driver_earning_id)
  select voucher_row.adda_id,p_voucher_id,id from unnest(coalesce(p_driver_earning_ids,array[]::uuid[])) id
  on conflict(voucher_id,driver_earning_id) do nothing;
end $$;

create or replace function public.ut_sync_voucher_cashbook(p_voucher_id text)
returns void language plpgsql security definer set search_path='' as $$
declare voucher_row record;voucher_total numeric;
begin
  perform pg_catalog.set_config('ut.cashbook_sync','on',true);
  select voucher.id,voucher.expense_no,coalesce(voucher.start_date,voucher.expense_date) accounting_date,
    voucher.loading_id,loading.vehicle_id,loading.driver_id into voucher_row
  from public.expenses voucher join public.loadings loading on loading.id=voucher.loading_id
  where voucher.id::text=p_voucher_id;
  if not found then
    delete from public.cashbook_entries where reference_type='voucher' and reference_id=p_voucher_id;
    return;
  end if;
  select coalesce(sum(item.amount),0) into voucher_total from public.expense_items item
  where item.expense_id=voucher_row.id and not(
    (item.expense_type='Workshop' and exists(select 1 from public.voucher_workshop_entries link where link.voucher_id=item.expense_id))
    or (item.expense_type='Oil / Lubricants' and exists(select 1 from public.voucher_oil_entries link where link.voucher_id=item.expense_id))
    or (item.expense_type='Tyre' and exists(select 1 from public.voucher_tyre_entries link where link.voucher_id=item.expense_id))
    or (item.expense_type='Driver Salary' and item.expense_class='vehicle_periodic' and exists(select 1 from public.voucher_driver_earnings link where link.voucher_id=item.expense_id))
  );
  if voucher_total::text in('NaN','Infinity','-Infinity') or voucher_total<0 then raise exception 'Voucher total cannot be negative'; end if;
  if voucher_total=0 then
    delete from public.cashbook_entries where reference_type='voucher' and reference_id=voucher_row.id::text;
    return;
  end if;
  update public.cashbook_entries set entry_date=voucher_row.accounting_date,entry_type='Cash Out',person_type='Other',person_name='Voucher',
    vehicle_id=voucher_row.vehicle_id,driver_id=voucher_row.driver_id,loading_id=voucher_row.loading_id,payment_method='Cash',amount=voucher_total,
    description='Voucher - '||coalesce(nullif(pg_catalog.btrim(voucher_row.expense_no),''),voucher_row.id::text),reference_type='voucher',reference_id=voucher_row.id::text
  where reference_type='voucher' and reference_id=voucher_row.id::text;
  if not found then
    insert into public.cashbook_entries(entry_date,entry_type,person_type,person_name,vehicle_id,driver_id,loading_id,payment_method,amount,description,reference_type,reference_id)
    values(voucher_row.accounting_date,'Cash Out','Other','Voucher',voucher_row.vehicle_id,voucher_row.driver_id,voucher_row.loading_id,'Cash',voucher_total,
      'Voucher - '||coalesce(nullif(pg_catalog.btrim(voucher_row.expense_no),''),voucher_row.id::text),'voucher',voucher_row.id::text);
  end if;
end $$;

