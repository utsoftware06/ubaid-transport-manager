"use client";

import type { DriverLedgerRow } from "./DriverLedger";

type Props = {
  rows: DriverLedgerRow[];
  selectedDriverName: string;
};

function formatAmount(value: number): string {
  return value.toLocaleString("en-PK", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  });
}

export default function DriverLedgerTable({
  rows,
  selectedDriverName,
}: Props) {
  function handlePrint() {
    if (rows.length === 0) return;

    const totalIncome = rows.reduce((sum, row) => sum + row.income, 0);
    const totalExpense = rows.reduce((sum, row) => sum + row.expense, 0);
    const netBalance = totalIncome - totalExpense;

    const rowsHtml = rows
      .map(
        (row) => `
        <tr>
          <td>${row.date}</td>
          <td>${row.loadingNo}</td>
          <td>${row.route}</td>
          <td>Rs. ${formatAmount(row.income)}</td>
          <td>Rs. ${formatAmount(row.expense)}</td>
          <td>Rs. ${formatAmount(row.balance)}</td>
        </tr>
      `
      )
      .join("");

    const printWindow = window.open("", "_blank", "width=1000,height=700");

    if (!printWindow) return;

    printWindow.document.write(`
      <!DOCTYPE html>
      <html>
        <head>
          <title>Driver Ledger</title>
          <style>
            body {
              font-family: Arial, sans-serif;
              padding: 30px;
              color: #111827;
            }
            h1 {
              text-align: center;
              margin-bottom: 5px;
            }
            .subtitle {
              text-align: center;
              margin-bottom: 25px;
              font-size: 14px;
            }
            .summary {
              display: grid;
              grid-template-columns: repeat(4, 1fr);
              gap: 10px;
              margin-bottom: 25px;
            }
            .box {
              border: 1px solid #d1d5db;
              padding: 12px;
              border-radius: 8px;
            }
            .box p {
              margin: 0;
              font-size: 13px;
              color: #374151;
            }
            .box h3 {
              margin: 6px 0 0;
              font-size: 18px;
            }
            table {
              width: 100%;
              border-collapse: collapse;
              font-size: 13px;
            }
            th, td {
              border: 1px solid #d1d5db;
              padding: 10px;
              text-align: left;
            }
            th {
              background: #f3f4f6;
            }
            .footer {
              margin-top: 30px;
              display: flex;
              justify-content: space-between;
              font-size: 13px;
            }
          </style>
        </head>
        <body>
          <h1>UT Software</h1>
          <div class="subtitle">
            Driver Ledger Report - ${selectedDriverName}
          </div>

          <div class="summary">
            <div class="box">
              <p>Total Trips</p>
              <h3>${rows.length}</h3>
            </div>
            <div class="box">
              <p>Total Income</p>
              <h3>Rs. ${formatAmount(totalIncome)}</h3>
            </div>
            <div class="box">
              <p>Total Expense</p>
              <h3>Rs. ${formatAmount(totalExpense)}</h3>
            </div>
            <div class="box">
              <p>Net Balance</p>
              <h3>Rs. ${formatAmount(netBalance)}</h3>
            </div>
          </div>

          <table>
            <thead>
              <tr>
                <th>Date</th>
                <th>Loading No</th>
                <th>Route</th>
                <th>Income</th>
                <th>Expense</th>
                <th>Balance</th>
              </tr>
            </thead>
            <tbody>
              ${rowsHtml}
            </tbody>
          </table>

          <div class="footer">
            <span>Generated by UT Software</span>
            <span>${new Date().toLocaleString("en-PK")}</span>
          </div>

          <script>
            window.onload = function() {
              window.print();
              window.onafterprint = function() {
                window.close();
              };
            };
          </script>
        </body>
      </html>
    `);

    printWindow.document.close();
  }

  return (
    <div className="rounded-xl bg-white p-6 shadow-md">
      <div className="mb-5 flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h2 className="text-xl font-bold text-gray-900">
            {selectedDriverName} Ledger Detail
          </h2>
          <p className="mt-1 text-sm font-medium text-gray-700">
            Driver ke trips, income, expense aur balance ki detail.
          </p>
        </div>

        <button
          type="button"
          onClick={handlePrint}
          disabled={rows.length === 0}
          className="rounded-lg bg-blue-600 px-5 py-2 text-sm font-bold text-white shadow-sm transition hover:bg-blue-700 disabled:cursor-not-allowed disabled:bg-gray-400"
        >
          🖨 Print Ledger
        </button>
      </div>

      {rows.length === 0 ? (
        <div className="rounded-lg border border-gray-200 bg-gray-50 p-8 text-center">
          <p className="font-semibold text-gray-900">
            Koi ledger record nahi mila.
          </p>
        </div>
      ) : (
        <div className="overflow-x-auto">
          <table className="min-w-full border-collapse text-sm text-gray-900">
            <thead>
              <tr className="bg-gray-100 text-left text-gray-900">
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Date</th>
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Loading No</th>
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Route</th>
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Income</th>
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Expense</th>
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Balance</th>
                <th className="border-b border-gray-300 px-4 py-3 font-bold">Status</th>
              </tr>
            </thead>

            <tbody>
              {rows.map((row) => {
                const isProfit = row.balance > 0;
                const isLoss = row.balance < 0;

                return (
                  <tr key={row.id} className="bg-white text-gray-900 hover:bg-gray-50">
                    <td className="border-b border-gray-200 px-4 py-3 font-medium">{row.date}</td>
                    <td className="border-b border-gray-200 px-4 py-3 font-semibold">{row.loadingNo}</td>
                    <td className="border-b border-gray-200 px-4 py-3 font-medium">{row.route}</td>
                    <td className="border-b border-gray-200 px-4 py-3 font-semibold">Rs. {formatAmount(row.income)}</td>
                    <td className="border-b border-gray-200 px-4 py-3 font-semibold">Rs. {formatAmount(row.expense)}</td>
                    <td className={`border-b border-gray-200 px-4 py-3 font-bold ${
                      isProfit ? "text-green-700" : isLoss ? "text-red-700" : "text-gray-900"
                    }`}>
                      Rs. {formatAmount(row.balance)}
                    </td>
                    <td className="border-b border-gray-200 px-4 py-3">
                      <span className={`rounded-full px-3 py-1 text-xs font-bold ${
                        isProfit ? "bg-green-100 text-green-700" : isLoss ? "bg-red-100 text-red-700" : "bg-gray-200 text-gray-800"
                      }`}>
                        {isProfit ? "Profit" : isLoss ? "Loss" : "Break Even"}
                      </span>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}